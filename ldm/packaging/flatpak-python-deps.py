#!/usr/bin/env python3
"""Write flatpak-python-deps.yml: LDM's Python dependencies as one pinned, offline Flatpak module.

    flatpak-python-deps.py RESOLVED.txt > flatpak-python-deps.yml
    flatpak-python-deps.py RESOLVED.txt --build-only python3-build-deps > flatpak-build-deps.yml

RESOLVED.txt lists the wheel files pip picks for the runtime's Python (PYTHON below: check it with
`flatpak run --command=python3 org.gnome.Sdk//51 --version`), made with pip only (wheels only, so no
package code runs while resolving):

    pip download --only-binary=:all: --python-version 3.14 --platform manylinux_2_28_x86_64 \\
        --platform manylinux_2_17_x86_64 --platform manylinux2014_x86_64 --dest /tmp/dl \\
        "httpx[socks]" dbus-fast dnspython secretstorage cryptography "yt-dlp[default]"
    ls /tmp/dl > RESOLVED.txt

Sources come from PyPI with their published SHA-256: pure-Python packages as their universal wheels,
compiled ones from source, except those in WHEELS (no Rust toolchain or Cython in the SDK), which use the
official manylinux wheels for each architecture.
"""

import json
import re
import sys
import urllib.request

WHEELS = {"cryptography", "dbus-fast"}
PYTHON = "cp314"  # the runtime's Python: GNOME 51 has 3.14
ARCHES = {"x86_64": "x86_64", "aarch64": "aarch64"}


def normalize(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def pypi_files(name: str, version: str) -> list[dict]:
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=30) as response:
        return json.load(response)["urls"]


def source(entry: dict, arch: str | None = None) -> dict:
    out = {"type": "file", "url": entry["url"], "sha256": entry["digests"]["sha256"]}
    if arch:
        out["only-arches"] = [arch]
    return out


def main() -> None:
    build_only = "--build-only" in sys.argv
    module = sys.argv[sys.argv.index("--build-only") + 1] if build_only else "python3-deps"
    resolved = sorted({
        (normalize(m.group(1)), m.group(2))
        for line in open(sys.argv[1]).read().split()
        if (m := re.match(r"([A-Za-z0-9_.]+?)-([0-9][^-]*)-", line))
    })
    sources = []
    for name, version in resolved:
        files = pypi_files(name, version)
        universal = [f for f in files if f["packagetype"] == "bdist_wheel" and f["filename"].endswith("-none-any.whl")]
        sdists = [f for f in files if f["packagetype"] == "sdist"]
        if universal:
            sources.append(source(universal[0]))
        elif name in WHEELS:
            for arch in ARCHES:
                wheels = [f for f in files if f["packagetype"] == "bdist_wheel" and "manylinux" in f["filename"]
                          and arch in f["filename"] and (f"{PYTHON}-{PYTHON}" in f["filename"] or "abi3" in f["filename"])]
                if not wheels:
                    sys.exit(f"{name} {version}: no manylinux wheel for {arch}")
                # The oldest glibc baseline that matches (the shortest tag list is the most specific one).
                sources.append(source(sorted(wheels, key=lambda f: f["filename"])[0], arch))
        elif sdists:
            sources.append(source(sdists[0]))
        else:
            sys.exit(f"{name} {version}: no source distribution on PyPI")
    names = " ".join(name for name, _ in resolved)
    print("# Generated by flatpak-python-deps.py from pip's resolution; do not edit by hand.")
    print(f"name: {module}")
    print("buildsystem: simple")
    print("build-commands:")
    print(f'  - pip3 install --verbose --exists-action=i --no-index --find-links="file://${{PWD}}" '
          f'--prefix=${{FLATPAK_DEST}} --no-build-isolation {names}')
    print("cleanup:")
    print('  - "*"' if build_only else "  - /bin")  # build tools: nothing of them stays in the app
    print("sources:")
    for s in sources:
        print(f"  - type: {s['type']}")
        print(f"    url: {s['url']}")
        print(f"    sha256: {s['sha256']}")
        if "only-arches" in s:
            print(f"    only-arches: [{s['only-arches'][0]}]")


if __name__ == "__main__":
    main()
